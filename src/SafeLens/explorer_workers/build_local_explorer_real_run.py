def _nla_compatibility(
    wrapper: HuggingFaceModelWrapper,
    layers: list[int],
) -> dict[str, Any]:
    profiles = list_nla_profiles()
    model_name = str(wrapper.name)
    d_model = int(wrapper.cfg.d_model or 0)
    rows: list[dict[str, Any]] = []
    for profile in profiles:
        base_model = str(profile["base_model"])
        profile_layer = int(profile["layer"])
        profile_d_model = int(profile["d_model"])
        model_matches = model_name.lower() == base_model.lower()
        layer_available = profile_layer in layers
        d_model_matches = profile_d_model == d_model
        structurally_compatible = model_matches and layer_available and d_model_matches
        status = "artifact_missing" if structurally_compatible else "incompatible"
        failures = []
        if not model_matches:
            failures.append(f"model requires {base_model}")
        if not layer_available:
            failures.append(f"layer L{profile_layer} is not cached")
        if not d_model_matches:
            failures.append(f"d_model requires {profile_d_model}, run has {d_model}")
        reason = (
            "Profile structure matches; AV/AR result artifact has not been generated."
            if structurally_compatible
            else "; ".join(failures)
        )
        rows.append(
            {
                "name": str(profile["name"]),
                "baseModel": base_model,
                "layer": profile_layer,
                "component": str(profile["component"]),
                "dModel": profile_d_model,
                "modelMatches": model_matches,
                "layerAvailable": layer_available,
                "dModelMatches": d_model_matches,
                "status": status,
                "reason": reason,
            }
        )
    return {
        "modelName": model_name,
        "dModel": d_model,
        "availableLayers": layers,
        "profiles": rows,
    }


def _normalize(values: list[float]) -> list[float]:
    bounds = _minmax(values)
    return [_normalize_one(value, bounds) for value in values]


def _normalize_one(value: float, bounds: tuple[float, float]) -> float:
    lo, hi = bounds
    if math.isclose(lo, hi, rel_tol=0.0, abs_tol=1e-12):
        return 0.0
    return max(0.0, min(1.0, (value - lo) / (hi - lo)))


def _minmax(values: list[float]) -> tuple[float, float]:
    if not values:
        return (0.0, 1.0)
    return (float(min(values)), float(max(values)))


def _round_score(value: float) -> float:
    return round(max(0.0, min(1.0, float(value))), 3)


def _top_indices(values: list[float], count: int) -> list[int]:
    return [
        index
        for index, _value in sorted(
            enumerate(values),
            key=lambda item: abs(float(item[1])),
            reverse=True,
        )[:count]
    ]


def _entropy(values: list[float]) -> float:
    total = sum(max(0.0, value) for value in values)
    if total <= 0:
        return 0.0
    entropy = 0.0
    for value in values:
        probability = max(0.0, value) / total
        if probability > 0:
            entropy -= probability * math.log(probability)
    return entropy


