def _attention_heads(
    cache: dict[str, Any],
    layers: list[int],
    token_texts: list[str],
    risk_indices: list[int],
) -> list[dict[str, Any]]:
    candidates: list[dict[str, Any]] = []
    risk_positions = risk_indices or [len(token_texts) - 1]
    for layer in layers:
        pattern = cache[f"blocks.{layer}.attn.hook_pattern"][0].float()
        for head in range(int(pattern.shape[0])):
            head_pattern = pattern[head]
            final_row = head_pattern[-1]
            risk_mass = float(final_row[risk_positions].sum().detach().cpu().item())
            entropy = _entropy(final_row.detach().cpu().tolist())
            candidates.append(
                {
                    "id": f"L{layer}H{head}",
                    "layer": layer,
                    "head": head,
                    "role": "real attention pattern",
                    "riskContribution": _round_score(risk_mass),
                    "entropy": round(entropy, 3),
                    "distributionByToken": [
                        [_round_score(float(value)) for value in row.detach().cpu().tolist()]
                        for row in head_pattern
                    ],
                }
            )
    selected: list[dict[str, Any]] = []
    for layer in layers:
        layer_candidates = [item for item in candidates if item["layer"] == layer]
        layer_candidates.sort(key=lambda item: item["riskContribution"], reverse=True)
        selected.extend(layer_candidates[:3])
    return selected


def _attention_cells(cache: dict[str, Any], layers: list[int]) -> list[dict[str, Any]]:
    cells: list[dict[str, Any]] = []
    for layer in layers:
        source_key = f"blocks.{layer}.attn.hook_pattern"
        pattern = cache[source_key][0].float()
        concentration = pattern.max(dim=-1).values.mean(dim=0).detach().cpu().tolist()
        for token_index, value in enumerate(concentration):
            cells.append(
                {
                    "layer": layer,
                    "tokenIndex": token_index,
                    "value": _round_score(float(value)),
                    "rawValue": round(float(value), 6),
                    "metric": "mean_head_max_source_attention",
                    "sourceKey": source_key,
                }
            )
    return cells


def _mlp_neurons(cache: dict[str, Any], layers: list[int]) -> list[dict[str, Any]]:
    candidates: list[dict[str, Any]] = []
    for layer in layers:
        signed_post = cache[f"layer_{layer}.post"][0].float()
        post = signed_post.abs()
        if post.ndim != 2:
            continue
        per_neuron = post.max(dim=0).values.detach().cpu().tolist()
        scale = max(per_neuron) if per_neuron else 1.0
        for neuron, value in enumerate(per_neuron):
            token_scores = post[:, neuron].detach().cpu().tolist()
            signed_token_scores = signed_post[:, neuron].detach().cpu().tolist()
            top_tokens = _top_indices(token_scores, 3)
            positive_top_tokens = sorted(
                range(len(signed_token_scores)),
                key=lambda index: signed_token_scores[index],
                reverse=True,
            )[:3]
            negative_top_tokens = sorted(
                range(len(signed_token_scores)),
                key=lambda index: signed_token_scores[index],
            )[:3]
            candidates.append(
                {
                    "id": f"L{layer}N{neuron:04d}",
                    "layer": layer,
                    "neuron": neuron,
                    "label": "real MLP post neuron",
                    "activation": _round_score(float(value) / max(scale, 1e-12)),
                    "riskContribution": _round_score(
                        sum(token_scores[index] for index in top_tokens)
                        / max(sum(token_scores), 1e-12)
                    ),
                    "topTokens": top_tokens,
                    "positiveTopTokens": positive_top_tokens,
                    "negativeTopTokens": negative_top_tokens,
                    "activationsByToken": [
                        round(float(activation), 6) for activation in signed_token_scores
                    ],
                    "maxAbsoluteActivation": round(float(value), 6),
                }
            )
    selected: list[dict[str, Any]] = []
    for layer in layers:
        layer_candidates = [item for item in candidates if item["layer"] == layer]
        layer_candidates.sort(key=lambda item: item["activation"], reverse=True)
        selected.extend(layer_candidates[:16])
    return selected


def _mlp_cells(cache: dict[str, Any], layers: list[int]) -> list[dict[str, Any]]:
    raw_cells: list[tuple[int, int, float, str]] = []
    for layer in layers:
        source_key = f"layer_{layer}.post"
        post = cache[source_key][0].float().abs()
        if post.ndim != 2:
            continue
        token_means = post.mean(dim=-1).detach().cpu().tolist()
        raw_cells.extend(
            (layer, token_index, float(value), source_key)
            for token_index, value in enumerate(token_means)
        )
    bounds = _minmax([value for _layer, _token, value, _key in raw_cells])
    return [
        {
            "layer": layer,
            "tokenIndex": token_index,
            "value": _round_score(_normalize_one(value, bounds)),
            "rawValue": round(value, 6),
            "metric": "mean_absolute_mlp_post_activation",
            "sourceKey": source_key,
        }
        for layer, token_index, value, source_key in raw_cells
    ]


